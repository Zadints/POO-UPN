    private void btnCalcularActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCalcularActionPerformed
try {
    double radio = Double.parseDouble(txtRadio.getText().trim());
    double altura = Double.parseDouble(txtAltura.getText().trim());
    com.mycompany.practicas.Semana5.Herencia.core.application.dto.CilindroDto dto = controller.calcularCilindro(radio, altura);
    java.text.DecimalFormatSymbols simbolos = new java.text.DecimalFormatSymbols(new java.util.Locale("es","PE"));
    simbolos.setDecimalSeparator(',');
    java.text.DecimalFormat df = new java.text.DecimalFormat("0.00", simbolos);
    txtArea.setText(df.format(dto.getArea()));
    txtVolumen.setText(df.format(dto.getVolumen()));
} catch (NumberFormatException ex) {
    javax.swing.JOptionPane.showMessageDialog(this, "Ingrese valores numericos validos");
}        // TODO add your handling code here:
    }//GEN-LAST:event_btnCalcularActionPerformed

